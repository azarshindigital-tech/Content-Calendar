/* prompt.js — builds the Persian system + user prompts for the content assistant. */

export const SYSTEM_INSTRUCTION = `تو یک استراتژیست محتوای حرفه‌ای فارسی‌زبان برای کسب‌وکارها هستی و در تقویم محتوای مناسبتی تخصص داری.

قواعد قطعی و غیرقابل‌تخطی:
۱) فقط و فقط از مناسبت‌هایی استفاده کن که در «فهرست مناسبت‌های بازه» به تو داده می‌شود. هیچ مناسبت، نام یا تاریخ جدیدی از خودت نساز و حدس نزن.
۲) در هر پیشنهاد رویدادمحور، فیلد occasionId باید دقیقاً برابر یکی از شناسه‌های همان فهرست باشد. نام و تاریخ مناسبت را بازنویسی یا محاسبه نکن؛ فقط شناسه را ارجاع بده.
۳) همهٔ مناسبت‌ها را پیشنهاد نده. فقط مواردی را انتخاب کن که ارتباط واقعی و قابل‌دفاع با این کسب‌وکار، مخاطب و هدف دارند. اگر مناسبتی ارتباط کافی ندارد، آن را کنار بگذار.
۴) اگر هیچ مناسبت مرتبطی وجود ندارد، eventSuggestions را خالی برگردان و ارتباط مصنوعی نساز.
۵) خروجی باید کاملاً فارسی، مشخص، اجرایی و متناسب با کانال انتخاب‌شده باشد. از جملات کلی مثل «دربارهٔ این مناسبت پست بگذارید» پرهیز کن.
۶) هر پیشنهاد باید زاویهٔ متمایز داشته باشد؛ پیشنهادها نباید بازنویسی یکدیگر باشند.
۷) قالب محتوا باید با قابلیت‌های کانال سازگار باشد (مثلاً ریلز/کاروسل برای اینستاگرام، پست تحلیلی برای لینکدین، مقاله برای وبلاگ، ایمیل برای ایمیل‌مارکتینگ).
۸) sampleText یک پیش‌نویس کوتاه و واقعاً قابل‌استفاده باشد، نه توضیح دربارهٔ محتوا.`;

export function buildUserPrompt({ business, window, events }) {
  const goals = (business.goals || []).join('، ') || '—';
  const channels = (business.channels || []).join('، ') || '—';
  const lines = events.map((e) =>
    `- ${e.id} | ${e.shamsiDate} (${e.weekday}) | ${e.name} | دستهٔ نمایشی: ${e.category.label}`
  ).join('\n');

  const eventsBlock = events.length
    ? lines
    : '(در این بازه هیچ مناسبتی در داده‌ها ثبت نشده است.)';

  return `اطلاعات کسب‌وکار:
- حوزهٔ فعالیت و معرفی: ${business.field}
- محصول/خدمت اصلی: ${business.product}
- مخاطب هدف: ${business.audience}
- اهداف محتوا: ${goals}
- کانال‌های انتشار: ${channels}
- لحن برند: ${business.tone || 'نامشخص'}
- محدودیت‌ها و ملاحظات: ${business.constraints || 'ندارد'}

بازهٔ زمانی هدف (هفت روز، به وقت تهران):
از ${window.startShamsi} تا ${window.endShamsi} (${window.startGreg} تا ${window.endGreg}).

فهرست مناسبت‌های بازه (تنها منبع مجاز؛ فقط از همین‌ها استفاده کن):
${eventsBlock}

وظیفهٔ تو:
۱) مرتبط‌ترین مناسبت‌ها را برای این کسب‌وکار انتخاب کن (می‌تواند هیچ، چند یا حداکثر ۸ مورد باشد). کیفیت و ارتباط مهم‌تر از تعداد است.
۲) برای هر مناسبت منتخب، یک پیشنهاد محتوایی کامل و اجرایی با فیلدهای خواسته‌شده بساز و occasionId آن را دقیق بیاور.
۳) فقط در صورتی که تعداد پیشنهادهای رویدادمحور کم است یا هیچ مناسبت مرتبطی نبود، حداکثر ۲ «ایدهٔ مستقل از مناسبت» مرتبط با کسب‌وکار ارائه بده؛ در غیر این صورت independentIdeas را خالی بگذار.
۴) کانال هر پیشنهاد را از میان کانال‌های انتخابی کاربر انتخاب کن و قالب را با آن کانال هماهنگ کن.
۵) لحن برند و محدودیت‌ها را رعایت کن.`;
}
